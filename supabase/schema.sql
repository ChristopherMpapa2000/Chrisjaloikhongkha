-- 1. ตารางเก็บกระทงและคำอธิษฐานจริง
CREATE TABLE IF NOT EXISTS public.krathongs (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
  wish TEXT NOT NULL CHECK (char_length(wish) BETWEEN 1 AND 240),
  location TEXT NOT NULL CHECK (location IN ('wat-arun', 'chiang-mai', 'sukhothai', 'khlong-ong-ang')),
  base_type TEXT NOT NULL CHECK (base_type IN ('banana-leaf', 'lotus', 'coconut', 'bread', 'royal-gold')),
  flower_type TEXT NOT NULL CHECK (flower_type IN ('marigold', 'orchid', 'pink-lotus', 'jasmine', 'rose')),
  candle_type TEXT NOT NULL CHECK (candle_type IN ('classic-gold', 'lotus-candle', 'twin-candle', 'lantern-mini')),
  ornament_type TEXT NOT NULL CHECK (ornament_type IN ('coins', 'gold-leaf', 'swan', 'garland', 'butterfly')),
  blessings INTEGER NOT NULL DEFAULT 0 CHECK (blessings >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_krathongs_location_created
  ON public.krathongs (location, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_krathongs_created
  ON public.krathongs (created_at DESC);

-- 2. ตารางประวัติการส่งคำอวยพร / ส่งใจ
CREATE TABLE IF NOT EXISTS public.blessings_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  krathong_id TEXT NOT NULL REFERENCES public.krathongs(id) ON DELETE CASCADE,
  reaction TEXT NOT NULL CHECK (reaction IN ('sathu', 'wish', 'health', 'love')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_blessings_krathong
  ON public.blessings_log (krathong_id);

-- 3. ตารางตัวนับกิจกรรมเทศกาล (เริ่มจาก 0 จริง ไม่มี Mock)
CREATE TABLE IF NOT EXISTS public.festival_counters (
  key TEXT PRIMARY KEY,
  count BIGINT NOT NULL DEFAULT 0 CHECK (count >= 0)
);

INSERT INTO public.festival_counters (key, count)
VALUES ('lanterns', 0), ('fireworks', 0)
ON CONFLICT (key) DO NOTHING;

-- 4. เปิด Row Level Security (RLS) เพื่อความปลอดภัยระดับ Production
-- (Node.js Backend จะเชื่อมต่อด้วย SUPABASE_SERVICE_ROLE_KEY ซึ่งผ่านสิทธิ์เซิร์ฟเวอร์โดยตรง
--  ทำให้ไม่มีใครยิงลบ/แก้ไขข้อมูลตรงจากหน้าเว็บเบราว์เซอร์ได้)
ALTER TABLE public.krathongs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.blessings_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.festival_counters ENABLE ROW LEVEL SECURITY;

-- ============================================================================
-- 5. Atomic PostgreSQL RPC Functions (รองรับคนกดพร้อมกันจำนวนมากไม่เกิด Race Condition)
-- ============================================================================

-- 5.1 ส่งคำอวยพรให้กระทงแบบ Atomic (เรียกได้เฉพาะฝั่งเซิร์ฟเวอร์ service_role เท่านั้น)
CREATE OR REPLACE FUNCTION public.bless_krathong(
  p_krathong_id TEXT,
  p_reaction TEXT DEFAULT 'sathu'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_safe_reaction TEXT;
  v_updated public.krathongs%ROWTYPE;
  v_reactions JSONB;
BEGIN
  v_safe_reaction := CASE
    WHEN p_reaction IN ('sathu', 'wish', 'health', 'love') THEN p_reaction
    ELSE 'sathu'
  END;

  UPDATE public.krathongs
  SET blessings = blessings + 1
  WHERE id = p_krathong_id
  RETURNING * INTO v_updated;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  INSERT INTO public.blessings_log (krathong_id, reaction)
  VALUES (p_krathong_id, v_safe_reaction);

  SELECT jsonb_build_object(
    'sathu', COALESCE(SUM(CASE WHEN reaction = 'sathu' THEN 1 ELSE 0 END), 0),
    'wish', COALESCE(SUM(CASE WHEN reaction = 'wish' THEN 1 ELSE 0 END), 0),
    'health', COALESCE(SUM(CASE WHEN reaction = 'health' THEN 1 ELSE 0 END), 0),
    'love', COALESCE(SUM(CASE WHEN reaction = 'love' THEN 1 ELSE 0 END), 0)
  )
  INTO v_reactions
  FROM public.blessings_log
  WHERE krathong_id = p_krathong_id;

  RETURN jsonb_build_object(
    'id', v_updated.id,
    'name', v_updated.name,
    'wish', v_updated.wish,
    'location', v_updated.location,
    'baseType', v_updated.base_type,
    'flowerType', v_updated.flower_type,
    'candleType', v_updated.candle_type,
    'ornamentType', v_updated.ornament_type,
    'blessings', v_updated.blessings,
    'createdAt', v_updated.created_at,
    'reactions', v_reactions
  );
END;
$$;

-- 5.2 เพิ่มตัวนับโคมลอย / พลุ แบบ Atomic
CREATE OR REPLACE FUNCTION public.increment_festival_counter(p_key TEXT)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_count BIGINT;
BEGIN
  IF p_key NOT IN ('lanterns', 'fireworks') THEN
    RETURN 0;
  END IF;

  INSERT INTO public.festival_counters (key, count)
  VALUES (p_key, 1)
  ON CONFLICT (key) DO UPDATE
    SET count = public.festival_counters.count + 1
  RETURNING count INTO v_count;

  RETURN v_count;
END;
$$;

-- 5.3 ดึงสถิติเทศกาลทั้งหมดใน Query เดียว (เร็วมากแม้มีกระทงหลายหมื่นใบ)
CREATE OR REPLACE FUNCTION public.get_festival_stats()
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  WITH k_stats AS (
    SELECT
      COUNT(*)::BIGINT AS total_krathongs,
      COALESCE(SUM(blessings), 0)::BIGINT AS total_blessings,
      COUNT(*) FILTER (WHERE location = 'wat-arun')::BIGINT AS wat_arun,
      COUNT(*) FILTER (WHERE location = 'chiang-mai')::BIGINT AS chiang_mai,
      COUNT(*) FILTER (WHERE location = 'sukhothai')::BIGINT AS sukhothai,
      COUNT(*) FILTER (WHERE location = 'khlong-ong-ang')::BIGINT AS khlong_ong_ang
    FROM public.krathongs
  ),
  c_stats AS (
    SELECT
      COALESCE(MAX(CASE WHEN key = 'lanterns' THEN count END), 0)::BIGINT AS lanterns,
      COALESCE(MAX(CASE WHEN key = 'fireworks' THEN count END), 0)::BIGINT AS fireworks
    FROM public.festival_counters
  )
  SELECT jsonb_build_object(
    'totalKrathongs', k.total_krathongs,
    'totalBlessings', k.total_blessings,
    'totalLanterns', c.lanterns,
    'totalFireworks', c.fireworks,
    'byLocation', jsonb_build_object(
      'wat-arun', k.wat_arun,
      'chiang-mai', k.chiang_mai,
      'sukhothai', k.sukhothai,
      'khlong-ong-ang', k.khlong_ong_ang
    )
  )
  FROM k_stats k, c_stats c;
$$;

-- จำกัดสิทธิ์ให้เฉพาะฝั่ง Backend (service_role) เท่านั้นที่เข้าถึงตารางและเรียก RPC ได้
-- (ปลอดภัยแม้ปิด "Grant API access to new tables automatically" ในหน้าสร้างโปรเจกต์)
GRANT USAGE ON SCHEMA public TO service_role;
GRANT ALL ON TABLE public.krathongs, public.blessings_log, public.festival_counters TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

REVOKE ALL ON FUNCTION public.bless_krathong(TEXT, TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.increment_festival_counter(TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.get_festival_stats() FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.bless_krathong(TEXT, TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.increment_festival_counter(TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.get_festival_stats() TO service_role;
